-- ============================================================
-- V6：补预约的治疗需求与就诊备注
-- 依据：报告 4.6 UC-02「字段列表」——
--       预约 = 预约编号 + 患者 + 诊所 + 就诊日期 + 就诊时间 + 接诊牙医
--              + {治疗需求}* + [就诊备注] + 预约状态 + 受理时间
--       其中“治疗需求”是一对多（带 * ）、“就诊备注”是单个可选项，
--       但报告 6.10 的 appointment 建表脚本只有标量字段，没有落这两项。
--       此处在库上补齐，并回写报告 6.9 数据字典与 6.10 建表脚本。
--
-- 为什么要单独建表而不是塞一列文本：
--   治疗需求参与 UC-02 规则 5 的资质匹配（牙医必须持有对应资质），
--   必须可被结构化查询；“大牙疼”这种自由文本无法参与匹配。
-- ============================================================

ALTER TABLE appointment ADD COLUMN note VARCHAR(120);

COMMENT ON COLUMN appointment.note IS '就诊备注（前台受理时记录的患者诉求补充说明）';

CREATE TABLE appointment_treatment (
  at_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id INTEGER NOT NULL,
  item_id        INTEGER NOT NULL,
  CONSTRAINT uk_appointment_item UNIQUE (appointment_id, item_id),
  CONSTRAINT fk_at_appointment FOREIGN KEY (appointment_id) REFERENCES appointment(appointment_id),
  CONSTRAINT fk_at_item        FOREIGN KEY (item_id)        REFERENCES treatment_item(item_id)
);

COMMENT ON TABLE  appointment_treatment IS '预约的治疗需求（一条预约可有多项）';
COMMENT ON COLUMN appointment_treatment.at_id          IS '关联编号';
COMMENT ON COLUMN appointment_treatment.appointment_id IS '预约编号（外键）';
COMMENT ON COLUMN appointment_treatment.item_id        IS '治疗项目编号（外键），参与资质匹配';
